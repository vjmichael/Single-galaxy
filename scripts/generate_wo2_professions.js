#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const path=require("node:path");
const {validateWO2}=require("./validate_wo2_professions.js");
function generate(catalog,wo2) {
  const checked=validateWO2(catalog,wo2);
  if(!checked.ok)throw Error(checked.errors.join("; "));
  const Q=JSON.stringify,lines=[];
  lines.push("// Generated by scripts/generate_wo2_professions.js from audited WO2 data.");
  lines.push("// Source-of-truth is data/industry/wo2_professions.json; never edit manually.");
  lines.push('#include "galaxy/WO2ProfessionCatalog.hpp"');
  lines.push("#include <stdexcept>");
  lines.push("#include <set>");
  lines.push("namespace galaxy::workforce02 {");
  lines.push("const std::vector<Trade>& trades(){static const std::vector<Trade> x={");
  for(const t of wo2.site_professions)
    lines.push("  {"+[
      Q(t.site_capability),Q(t.profession),Q(t.skill_family),Q(t.level),
      t.minimum_workers+"u",t.training_units+"u",Q(t.training_policy),
      Q(t.native_binding||""),t.power_required?"true":"false",
      t.effect_authority==="original_simulation"?"true":"false"].join(",")+"},");
  lines.push("};return x;}");
  lines.push("const std::vector<ServiceRole>& service_roles(){static const std::vector<ServiceRole> x={");
  for(const t of wo2.service_roles)
    lines.push("  {"+[
      Q(t.staff_role),Q(t.profession),Q(t.skill_family),Q(t.level),
      t.training_units+"u"].join(",")+"},");
  lines.push("};return x;}");
  lines.push("const Trade* find_trade(const std::string& code) noexcept {");
  lines.push("  for(const auto& row:trades())if(row.capability==code)return &row;");
  lines.push("  return nullptr;}");
  lines.push("const ServiceRole* find_service_role(const std::string& code) noexcept {");
  lines.push("  for(const auto& row:service_roles())if(row.staff_role==code)return &row;");
  lines.push("  return nullptr;}");
  lines.push("void validate_against_industry01(){");
  lines.push("  industry01::validate_against_original_inventory();");
  lines.push("  std::set<std::string> sites,staff;");
  lines.push("  unsigned native=0;");
  lines.push("  for(const auto& t:trades()){");
  lines.push("    if(!sites.insert(t.capability).second || !t.minimum_workers || !t.power_required)");
  lines.push("      throw std::invalid_argument(\"WO2 invalid profession capacity\");");
  lines.push("    if(t.native_execution){");
  lines.push("      ++native;");
  lines.push("      const bool cut=t.capability==\"cut\",shape=t.capability==\"shape\";");
  lines.push("      if((!cut&&!shape)||t.level!=\"native_baseline\"||t.minimum_workers!=1||t.training_units!=0||");
  lines.push("         t.native_binding!=(cut?\"native_cut_aluminum_panel\":\"native_shape_aluminum_frame\")||");
  lines.push("         !industry01::is_native_workshop_recipe(t.native_binding))");
  lines.push("         throw std::invalid_argument(\"WO2 unauthorized native work binding\");");
  lines.push("    }else if(!t.native_binding.empty()||t.level==\"native_baseline\")");
  lines.push("      throw std::invalid_argument(\"WO2 fake qualified worker\");");
  lines.push("  }");
  lines.push("  if(native!=2)throw std::invalid_argument(\"WO2 unexpected native executor count\");");
  lines.push("  for(const auto& r:industry01::recipes()){");
  lines.push("    if(!find_trade(r.site_capability))throw std::invalid_argument(\"WO2 recipe has no profession\");}");
  lines.push("  for(const auto& r:industry01::recovery_recipes()){");
  lines.push("    if(!find_trade(r.recipe.site_capability))throw std::invalid_argument(\"WO2 recovery has no profession\");}");
  lines.push("  for(const auto& r:service_roles()){");
  lines.push("    if(!staff.insert(r.staff_role).second)throw std::invalid_argument(\"WO2 duplicate service worker\");}");
  lines.push("  for(const auto& svc:industry01::services()){");
  lines.push("    for(const auto& role:svc.staff)");
  lines.push("      if(!find_service_role(role))throw std::invalid_argument(\"WO2 service staff missing\");");
  lines.push("  }");
  lines.push("}");
  lines.push("} // namespace galaxy::workforce02");
  return lines.join("\n")+"\n";
}
module.exports={generate};
if(require.main===module){
  const root=path.join(__dirname,"..");
  const catalog=JSON.parse(fs.readFileSync(path.join(root,"data/industry/industry01_candidate_catalog.json"),"utf8"));
  const wo2=JSON.parse(fs.readFileSync(path.join(root,"data/industry/wo2_professions.json"),"utf8"));
  const generated=generate(catalog,wo2);
  const dest=path.join(root,"src/WO2ProfessionCatalog.generated.cpp");
  if(process.argv.includes("--check")){
    if(fs.readFileSync(dest,"utf8")!==generated)throw Error("WO2 generated native profiles stale");
    console.log("WO2 C++ profession profiles match source catalogue");
  }else{
    fs.writeFileSync(dest,generated);
    console.log("WO2 generated native profession profiles refreshed");
  }
}

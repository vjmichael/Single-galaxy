#!/usr/bin/env node
"use strict";
// Deterministic, offline C++ registry generation from the audited JSON.
// This is a build-time materialization of catalogue DATA, never a world writer.
const fs=require("node:fs");
const path=require("node:path");
const {validateCatalog,validateLegacyUnits}=require("./validate_industry01.js");
const Q=JSON.stringify;
function generateCatalog(c,audit){
  const r=validateCatalog(c),l=validateLegacyUnits(c,audit);
  if(!r.ok||!l.ok)throw Error([...r.errors,...l.errors].join("; "));
  const vec=x=>"{"+x.map(v=>Q(v)).join(",")+"}";
  const ls=x=>"{"+x.map(v=>"{"+Q(v.item)+","+v.qty+"ULL}").join(",")+"}";
  const out=[];
  out.push("// GENERATED by scripts/generate_industry01_cpp.js from the validated");
  out.push("// data/industry/industry01_candidate_catalog.json and industry01_legacy_units.json.");
  out.push("// Do not edit: run node scripts/generate_industry01_cpp.js");
  out.push('#include "galaxy/Industry01Catalog.hpp"');
  out.push('#include "galaxy/Inventory.hpp"');
  out.push("#include <algorithm>");
  out.push("#include <limits>");
  out.push("#include <stdexcept>");
  out.push("#include <map>");
  out.push("#include <set>");
  out.push("namespace galaxy::industry01 {");
  out.push("const std::vector<Item>& items(){static const std::vector<Item> x={");
  for(const a of c.items)out.push("  {"+[Q(a.id),Q(a.group),Q(a.unit),Q(a.lifecycle),a.mass_g_per_unit+"ULL",a.cargo_mm3_per_unit+"ULL",vec(a.need_tags)].join(",")+"},");
  out.push("};return x;}");
  out.push("const std::vector<Recipe>& recipes(){static const std::vector<Recipe> x={");
  for(const a of c.recipes)out.push("  {"+[Q(a.id),Q(a.site_capability),a.work_ticks+"ULL",a.energy_kj+"ULL",ls(a.inputs),ls(a.outputs),Q(a.native_production_binding||"")].join(",")+"},");
  out.push("};return x;}");
  out.push("const std::vector<Service>& services(){static const std::vector<Service> x={");
  for(const a of c.services)out.push("  {"+[Q(a.id),Q(a.result),vec(a.staff),vec(a.site_capabilities),vec(a.input_consumables),vec(a.durable_requirements)].join(",")+"},");
  out.push("};return x;}");
  out.push("const std::vector<LegacyUnit>& legacy_units(){static const std::vector<LegacyUnit> x={");
  for(const a of audit.rows)out.push("  {"+[Q(a.legacy_code),Q(a.kind),Q(a.original_source_field),a.storage_litres_per_unit+"ULL",a.mass_g_per_unit+"ULL"].join(",")+"},");
  out.push("};return x;}");
  out.push("const Item* find_item(const std::string& id) noexcept {for(const auto& x:items())if(x.code==id)return &x;return nullptr;}");
  out.push("const Recipe* find_recipe(const std::string& id) noexcept {for(const auto& x:recipes())if(x.code==id)return &x;return nullptr;}");
  out.push("const Service* find_service(const std::string& id) noexcept {for(const auto& x:services())if(x.code==id)return &x;return nullptr;}");
  out.push("bool is_native_workshop_recipe(const std::string& id) noexcept {");
  out.push("  const auto* r=find_recipe(id);return r && ((id==\"native_cut_aluminum_panel\" && r->native_binding==\"original_quantified_line_panel\") ||");
  out.push("    (id==\"native_shape_aluminum_frame\" && r->native_binding==\"original_quantified_line_frame\"));");
  out.push("}");
  out.push("industry::Recipe original_workshop_recipe(const std::string& id) {");
  out.push("  const auto* r=find_recipe(id);");
  out.push("  if(!r || !is_native_workshop_recipe(id) || r->inputs.size()!=1 || r->outputs.size()!=2)");
  out.push("    throw std::invalid_argument(\"INDUSTRY-01 is not an authorized original workshop recipe\");");
  out.push("  auto trim=[](const std::string& s){if(s.rfind(\"bulk/\",0)!=0)throw std::invalid_argument(\"non-bulk original work item\");return s.substr(5);};");
  out.push("  auto mass=[](std::uint64_t x){if(x>static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max()))");
  out.push("    throw std::overflow_error(\"industry recipe quantity too large\");return static_cast<std::int64_t>(x);};");
  out.push("  if(r->outputs[1].code!=\"bulk/aluminum_scrap\" || r->work_ticks!=5 ||");
  out.push("     (r->site_capability!=\"cut\" && r->site_capability!=\"shape\"))");
  out.push("    throw std::invalid_argument(\"native recipe no longer matches original workshop contract\");");
  out.push("  const std::string name=id==\"native_cut_aluminum_panel\"?\"aluminum_panel\":\"aluminum_frame\";");
  out.push("  return {name,r->site_capability,{{trim(r->inputs[0].code),mass(r->inputs[0].quantity)}},");
  out.push("    {trim(r->outputs[0].code),mass(r->outputs[0].quantity)},");
  out.push("    {trim(r->outputs[1].code),mass(r->outputs[1].quantity)}};");
  out.push("}");
  out.push("void validate_against_original_inventory(){");
  out.push("  const auto& original=inventory::Catalogue::standard();");
  out.push("  std::set<std::string> ids;");
  out.push("  for(const auto& x:items()){if(x.code.empty() || x.mass_g_per_unit==0 || x.cargo_mm3_per_unit==0 || !ids.insert(x.code).second)");
  out.push("    throw std::invalid_argument(\"invalid generated industry item\");}");
  out.push("  for(const auto& r:recipes()){");
  out.push("    if(r.code.empty() || r.work_ticks==0 || r.inputs.empty() || r.outputs.empty())throw std::invalid_argument(\"invalid industry recipe\");");
  out.push("    auto mass=[](const std::vector<Ingredient>& lines){std::uint64_t sum=0;std::set<std::string> seen;");
  out.push("      for(const auto& line:lines){const auto* x=find_item(line.code);");
  out.push("        if(!x || !line.quantity || !seen.insert(line.code).second ||");
  out.push("           line.quantity>std::numeric_limits<std::uint64_t>::max()/x->mass_g_per_unit)");
  out.push("          throw std::invalid_argument(\"invalid material or overflow\");");
  out.push("        const auto add=line.quantity*x->mass_g_per_unit;");
  out.push("        if(add>std::numeric_limits<std::uint64_t>::max()-sum)throw std::overflow_error(\"recipe mass overflow\");");
  out.push("        sum+=add;}return sum;};");
  out.push("    if(mass(r.inputs)!=mass(r.outputs))throw std::invalid_argument(\"industry physical mass imbalance\");");
  out.push("  }");
  out.push("  ids.clear();");
  out.push("  if(legacy_units().size()!=28)throw std::invalid_argument(\"legacy inventory code count changed\");");
  out.push("  for(const auto& x:legacy_units()){if(!ids.insert(x.code).second ||");
  out.push("    original.liters_per_unit(x.code)!=static_cast<std::int64_t>(x.storage_liters_per_unit) || !x.mass_g_per_unit)");
  out.push("    throw std::invalid_argument(\"legacy inventory audit diverges from original game\");}");
  out.push("  for(const char* id:{\"native_cut_aluminum_panel\",\"native_shape_aluminum_frame\"}){");
  out.push("    const auto recipe=original_workshop_recipe(id);");
  out.push("    industry::State s;s.feed.capacity_grams=1000000;");
  out.push("    s.finished.capacity_grams=1000000;s.scrap.capacity_grams=1000000;");
  out.push("    industry::QuantifiedLine line(recipe,{1,recipe.operation,true,true,true},s);");
  out.push("    if(line.cycle_ticks()!=5)throw std::invalid_argument(\"original factory cycle mismatch\");");
  out.push("  }");
  out.push("}");
  out.push("} // namespace galaxy::industry01");
  return out.join("\n")+"\n";
}
module.exports={generateCatalog};
if(require.main===module) {
  const root=path.join(__dirname,"..");
  const c=JSON.parse(fs.readFileSync(path.join(root,"data/industry/industry01_candidate_catalog.json"),"utf8"));
  const audit=JSON.parse(fs.readFileSync(path.join(root,"data/industry/industry01_legacy_units.json"),"utf8"));
  const file=path.join(root,"src/Industry01Catalog.generated.cpp");
  const generated=generateCatalog(c,audit);
  if(process.argv.includes("--check")) {
    if(fs.readFileSync(file,"utf8")!==generated)throw Error("Generated C++ registry is stale");
    console.log("INDUSTRY-01 generated C++ matches source data");
  } else {
    fs.writeFileSync(file,generated);
    console.log("INDUSTRY-01 generated C++ registry refreshed");
  }
}
